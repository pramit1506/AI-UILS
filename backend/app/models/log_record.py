import uuid
from datetime import datetime, timezone
from sqlalchemy import String, Text, DateTime
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column
from app.database.base import Base
from app.database.mixins import UUIDMixin, TimestampMixin


class LogRecord(UUIDMixin, TimestampMixin, Base):
    """
    Universal log record for any document/schema type.
    Stores extracted fields as a flexible JSONB blob alongside schema metadata.
    """
    __tablename__ = "log_record"

    # Schema / domain identification
    schema_name: Mapped[str] = mapped_column(String(100), index=True)
    domain: Mapped[str | None] = mapped_column(String(100), index=True)

    # Human-readable reference identifier (e.g. LOG-ABC12345)
    log_reference: Mapped[str] = mapped_column(String(80), unique=True, index=True)

    # The flexible JSON payload — stores all extracted field-value pairs
    data: Mapped[dict] = mapped_column(JSONB, nullable=False, default=dict)

    # AI confidence metadata per field
    field_metadata: Mapped[dict] = mapped_column(JSONB, nullable=False, default=dict)

    # Free-text summary of the log (auto-generated by the AI)
    summary: Mapped[str | None] = mapped_column(Text)

    # Source of the information (e.g. "pdf", "text", "email")
    source: Mapped[str | None] = mapped_column(String(50))

    # Conversation that created this log
    conversation_id: Mapped[str | None] = mapped_column(String(100), index=True)
